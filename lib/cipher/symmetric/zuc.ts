const MOD = (1n << 31n) - 1n

function addMod(a: bigint, b: bigint): bigint {
    let res = a + b
    if (res >= MOD) res -= MOD
    return res
}

function mulMod(a: bigint, c: bigint): bigint {
    return (a * c) % MOD
}

