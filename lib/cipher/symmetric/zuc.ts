function parseHex(s: string, lbl: string): number[] {
    const c = s.replace(/\s+/g, '').toLowerCase()
    if (!/^[0-9a-f]*$/.test(c) || c.length % 2 !== 0) throw new CipherError('INVALID_INPUT', `${lbl} must be hex.`)
    const o: number[] = []
    for (let i = 0; i < c.length; i += 2) o.push(parseInt(c.slice(i, i + 2), 16))
    return o
}

function toHex(b: number[]): string {
    return b.map(x => x.toString(16).padStart(2, '0')).join('')
}

function zucCore(input: string, key: string, iv: string, instrument: boolean): CipherResult {
    const start = performance.now()
    validateKey(key)
    const keyBytes = parseHex(key, 'ZUC key')
    if (keyBytes.length !== 16) throw new CipherError('INVALID_KEY_LENGTH', 'ZUC key must be 128 bits.')
    const ivBytes = parseHex(iv || '00'.repeat(16), 'ZUC IV')
    if (ivBytes.length !== 16) throw new CipherError('INVALID_INPUT', 'ZUC IV must be 128 bits.')
    const inBytes = parseHex(input, 'ZUC input')

    // LFSR Initialization (16 stages of 31-bit values)
    const LFSR: bigint[] = new Array(16).fill(1n)
    for (let i = 0; i < 16; i++) {
        let val = BigInt(keyBytes[i]) << 23n
        val |= BigInt(ivBytes[i]) << 8n
        val |= BigInt(((i * 15) + 7) & 0xFF) // Simplified constant D
        if (val === 0n) val = MOD
        LFSR[i] = val % MOD
    }

    let R1 = 0, R2 = 0

    const steps: CipherStep[] = []
    if (instrument) {
        steps.push({ index: 0, label: 'Initialization', inputState: `Key: ${toHex(keyBytes)}`, outputState: 'LFSR loaded mod 2^31-1', note: 'ZUC uses modular arithmetic over the Mersenne prime 2^31-1, NOT simple XOR feedback.', isMilestone: true })
    }

    // 32 Initialization Rounds (Feedback into LFSR)
    for (let i = 0; i < 32; i++) {
        // Bit Reorganization
        const X0 = Number(((LFSR[15] >> 15n) & 0xFFFFn) << 16n | (LFSR[14] & 0xFFFFn))
        const X1 = Number((LFSR[11] & 0xFFFFn) << 16n | ((LFSR[9] >> 15n) & 0xFFFFn))
        const X2 = Number((LFSR[7] & 0xFFFFn) << 16n | ((LFSR[5] >> 15n) & 0xFFFFn))
        const X3 = Number((LFSR[2] & 0xFFFFn) << 16n | ((LFSR[0] >> 15n) & 0xFFFFn))

        // FSM
        const W = (((X0 ^ R1) >>> 0) + R2) >>> 0
        const W1 = (R1 + X1) >>> 0
        const W2 = (R2 ^ X2) >>> 0

        const w1_bytes = [(W1 >>> 24) & 0xFF, (W1 >>> 16) & 0xFF, (W1 >>> 8) & 0xFF, W1 & 0xFF]
        const w2_bytes = [(W2 >>> 24) & 0xFF, (W2 >>> 16) & 0xFF, (W2 >>> 8) & 0xFF, W2 & 0xFF]

        R1 = ((S0[w1_bytes[0]] << 24) | (S1[w1_bytes[1]] << 16) | (S0[w1_bytes[2]] << 8) | S1[w1_bytes[3]]) >>> 0
        R2 = ((S0[w2_bytes[0]] << 24) | (S1[w2_bytes[1]] << 16) | (S0[w2_bytes[2]] << 8) | S1[w2_bytes[3]]) >>> 0

        // LFSR Feedback (mod 2^31 - 1)
        let v = addMod(mulMod(LFSR[15], 1n << 15n), mulMod(LFSR[13], 1n << 17n))
        v = addMod(v, mulMod(LFSR[10], 1n << 21n))
        v = addMod(v, mulMod(LFSR[4], 1n << 20n))
        v = addMod(v, mulMod(LFSR[0], 1n + (1n << 8n)))

        // Feed W back into LFSR during init
        v = addMod(v, BigInt(W >>> 1))

        if (v === 0n) v = MOD

        for (let j = 0; j < 15; j++) LFSR[j] = LFSR[j + 1]
        LFSR[15] = v
    }

    // Keystream Generation
    const outBuf: number[] = []
    for (let i = 0; i < inBytes.length; i += 4) {
        const X0 = Number(((LFSR[15] >> 15n) & 0xFFFFn) << 16n | (LFSR[14] & 0xFFFFn))
        const X1 = Number((LFSR[11] & 0xFFFFn) << 16n | ((LFSR[9] >> 15n) & 0xFFFFn))
        const X2 = Number((LFSR[7] & 0xFFFFn) << 16n | ((LFSR[5] >> 15n) & 0xFFFFn))
        const X3 = Number((LFSR[2] & 0xFFFFn) << 16n | ((LFSR[0] >> 15n) & 0xFFFFn))

        const W = (((X0 ^ R1) >>> 0) + R2) >>> 0
        const Z = (W ^ X3) >>> 0

        const W1 = (R1 + X1) >>> 0
        const W2 = (R2 ^ X2) >>> 0
        const w1_bytes = [(W1 >>> 24) & 0xFF, (W1 >>> 16) & 0xFF, (W1 >>> 8) & 0xFF, W1 & 0xFF]
        const w2_bytes = [(W2 >>> 24) & 0xFF, (W2 >>> 16) & 0xFF, (W2 >>> 8) & 0xFF, W2 & 0xFF]
        R1 = ((S0[w1_bytes[0]] << 24) | (S1[w1_bytes[1]] << 16) | (S0[w1_bytes[2]] << 8) | S1[w1_bytes[3]]) >>> 0
        R2 = ((S0[w2_bytes[0]] << 24) | (S1[w2_bytes[1]] << 16) | (S0[w2_bytes[2]] << 8) | S1[w2_bytes[3]]) >>> 0

        let v = addMod(mulMod(LFSR[15], 1n << 15n), mulMod(LFSR[13], 1n << 17n))
        v = addMod(v, mulMod(LFSR[10], 1n << 21n))
        v = addMod(v, mulMod(LFSR[4], 1n << 20n))
        v = addMod(v, mulMod(LFSR[0], 1n + (1n << 8n)))
        if (v === 0n) v = MOD
        for (let j = 0; j < 15; j++) LFSR[j] = LFSR[j + 1]
        LFSR[15] = v

        const z_bytes = [(Z >>> 24) & 0xFF, (Z >>> 16) & 0xFF, (Z >>> 8) & 0xFF, Z & 0xFF]
        for (let b = 0; b < 4 && (i + b) < inBytes.length; b++) {
            outBuf.push(inBytes[i + b] ^ z_bytes[b])
        }
    }

    if (instrument) {
        steps.push({ index: 1, label: 'Keystream Generation', inputState: toHex(inBytes), outputState: toHex(outBuf), note: 'FSM produces 32-bit words XORed with plaintext.', isMilestone: true })
    }

    return { output: toHex(outBuf), outputEncoding: 'hex', steps, metadata: METADATA, durationMs: performance.now() - start }
}

export function encrypt(input: string, key: string, options: CipherOptions = {}): CipherResult {
    validateInput(input)
    return zucCore(input, key, options.iv as string || '', !!options.instrument)
}

export function decrypt(input: string, key: string, options: CipherOptions = {}): CipherResult {
    validateInput(input)
    return zucCore(input, key, options.iv as string || '', !!options.instrument)
}

