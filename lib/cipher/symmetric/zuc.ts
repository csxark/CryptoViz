/**
 * ZUC — Chinese National Stream Cipher (GB/T 33133).
 * Used in 4G LTE (128-EEA3 / 128-EIA3).
 * 
 * Defining feature: 16-stage LFSR over GF(2^31 - 1).
 * Unlike Trivium/Grain/A5-1 which use GF(2) XOR feedback, ZUC uses
 * modular arithmetic over the Mersenne prime 2^31 - 1.
 */
